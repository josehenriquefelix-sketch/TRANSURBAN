begin;
create table if not exists public.tu_perfil (
  usuario_id uuid primary key references auth.users(id) on delete cascade,
  nome text not null,
  email text not null,
  cpf_hash text unique check (cpf_hash ~ '^[0-9a-f]{64}$'),
  criado_em timestamptz not null default now()
);
create table if not exists public.tu_carteira (
  usuario_id uuid primary key references auth.users(id) on delete cascade,
  numero bigint generated always as identity unique,
  saldo_centavos bigint not null default 0 check (saldo_centavos between 0 and 100000)
);
create table if not exists public.tu_recarga (
  id bigint generated always as identity primary key,
  usuario_id uuid not null references public.tu_carteira(usuario_id) on delete cascade,
  valor_centavos integer not null check (valor_centavos between 500 and 20000),
  chave uuid not null unique,
  criado_em timestamptz not null default now()
);
create table if not exists public.tu_trajeto (
  id integer generated by default as identity primary key,
  nome text not null,
  origem text not null,
  destino text not null,
  duracao_min integer not null check (duracao_min > 0),
  paradas jsonb not null,
  fonte text not null default 'Programação sintética acadêmica'
);
create table if not exists public.tu_horario (
  id integer generated by default as identity primary key,
  trajeto_id integer not null references public.tu_trajeto(id) on delete restrict,
  partida time not null,
  dias_semana integer[] not null default array[1,2,3,4,5,6,7],
  veiculo text not null,
  motorista text not null,
  unique(trajeto_id, partida)
);
create table if not exists public.tu_avaliacao (
  id bigint generated always as identity primary key,
  usuario_id uuid not null references auth.users(id) on delete cascade,
  horario_id integer not null references public.tu_horario(id) on delete restrict,
  dia date not null,
  nota_onibus integer not null check (nota_onibus between 1 and 5),
  nota_motorista integer not null check (nota_motorista between 1 and 5),
  comentario text not null default '' check(length(comentario) <= 1000),
  criado_em timestamptz not null default now(),
  unique(usuario_id, horario_id, dia)
);
create index if not exists tu_avaliacao_usuario on public.tu_avaliacao(usuario_id, criado_em desc);
create index if not exists tu_recarga_usuario on public.tu_recarga(usuario_id, criado_em desc);
create or replace function public.tu_criar_conta() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.tu_perfil(usuario_id,nome,email,cpf_hash)
  values(new.id,coalesce(new.raw_user_meta_data->>'nome','Passageiro'),new.email,new.raw_user_meta_data->>'cpf_hash');
  insert into public.tu_carteira(usuario_id) values(new.id);
  return new;
end; $$;
drop trigger if exists tu_nova_conta on auth.users;
create trigger tu_nova_conta after insert on auth.users for each row execute function public.tu_criar_conta();
-- Contas que já existiam também recebem carteira, sem alterar seus dados.
