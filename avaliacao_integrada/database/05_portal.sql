create or replace function public.tu_recarregar_demo(p_usuario uuid,p_valor integer,p_chave uuid)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare saldo bigint; anterior public.tu_recarga;
begin
  if p_valor < 500 or p_valor > 20000 then raise exception 'Valor inválido'; end if;
  select saldo_centavos into saldo from public.tu_carteira where usuario_id=p_usuario for update;
  if not found then raise exception 'Carteira inexistente'; end if;
  select * into anterior from public.tu_recarga where chave=p_chave;
  if found then
    if anterior.usuario_id <> p_usuario or anterior.valor_centavos <> p_valor then
      raise exception 'Chave de operação já utilizada';
    end if;
    return jsonb_build_object('id',anterior.id,'saldo_centavos',saldo,'repetida',true);
  end if;
  if saldo + p_valor > 100000 then raise exception 'Limite demonstrativo de R$ 1.000 atingido'; end if;
  insert into public.tu_recarga(usuario_id,valor_centavos,chave) values(p_usuario,p_valor,p_chave) returning * into anterior;
  update public.tu_carteira set saldo_centavos=saldo_centavos+p_valor where usuario_id=p_usuario returning saldo_centavos into saldo;
  return jsonb_build_object('id',anterior.id,'saldo_centavos',saldo,'repetida',false);
end; $$;
revoke all on function public.tu_recarregar_demo(uuid,integer,uuid) from public, anon, authenticated;
