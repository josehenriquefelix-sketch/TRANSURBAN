-- TRANSURBAN | criar APENAS em banco de demonstração vazio, após a tabela cidade.
-- Esta entidade tem chave estrangeira; a recuperação de backend exige CRUD completo apenas para cidade.
CREATE TABLE public.linha_onibus (
    id_linha INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cidade INTEGER NOT NULL REFERENCES public.cidade(id_cidade),
    codigo VARCHAR(20) NOT NULL,
    nome VARCHAR(120) NOT NULL,
    CONSTRAINT uq_linha_cidade_codigo UNIQUE (id_cidade, codigo)
);

CREATE INDEX ix_linha_onibus_id_cidade ON public.linha_onibus(id_cidade);
ALTER TABLE public.linha_onibus ENABLE ROW LEVEL SECURITY;
GRANT ALL ON TABLE public.linha_onibus TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.linha_onibus_id_linha_seq TO service_role;
