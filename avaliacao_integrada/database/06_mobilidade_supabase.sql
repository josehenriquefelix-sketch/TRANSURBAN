BEGIN;
CREATE TABLE IF NOT EXISTS public.transurban_gps (
 veiculo text PRIMARY KEY CHECK (veiculo ~ '^[A-Z0-9-]{1,20}$'),
 linha text NOT NULL CHECK (linha ~ '^[A-Z0-9-]{1,20}$'),
 latitude double precision NOT NULL CHECK (latitude BETWEEN -90 AND 90),
 longitude double precision NOT NULL CHECK (longitude BETWEEN -180 AND 180),
 precisao double precision NOT NULL CHECK (precisao BETWEEN 0 AND 10000),
 gps_em double precision NOT NULL,
 recebido double precision NOT NULL
);
CREATE TABLE IF NOT EXISTS public.transurban_avaliacoes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 veiculo text NOT NULL CHECK (veiculo ~ '^[A-Z0-9-]{1,20}$'),
 linha text NOT NULL CHECK (linha ~ '^[A-Z0-9-]{1,20}$'),
 nota smallint NOT NULL CHECK (nota BETWEEN 1 AND 5),
 lotacao text NOT NULL CHECK (lotacao IN ('Vazio','Normal','Cheio')),
 descricao text NOT NULL CHECK (char_length(trim(descricao)) BETWEEN 3 AND 400),
 criado double precision NOT NULL
);
CREATE INDEX IF NOT EXISTS transurban_gps_linha ON public.transurban_gps(linha, gps_em);
CREATE INDEX IF NOT EXISTS transurban_avaliacoes_linha ON public.transurban_avaliacoes(linha, id DESC);
ALTER TABLE public.transurban_gps ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transurban_avaliacoes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.transurban_gps, public.transurban_avaliacoes FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.transurban_gps TO service_role;
GRANT SELECT, INSERT ON public.transurban_avaliacoes TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.transurban_avaliacoes_id_seq TO service_role;
CREATE OR REPLACE FUNCTION public.transurban_publicar_gps(leitura jsonb)
RETURNS void LANGUAGE sql SECURITY INVOKER SET search_path = '' AS $$
 INSERT INTO public.transurban_gps AS gps (veiculo,linha,latitude,longitude,precisao,gps_em,recebido)
 SELECT p.veiculo,p.linha,p.latitude,p.longitude,p.precisao,p.gps_em,p.recebido
 FROM jsonb_populate_record(NULL::public.transurban_gps, leitura) AS p
 ON CONFLICT (veiculo) DO UPDATE SET
 linha=excluded.linha, latitude=excluded.latitude, longitude=excluded.longitude,
 precisao=excluded.precisao, gps_em=excluded.gps_em, recebido=excluded.recebido
 WHERE excluded.gps_em >= gps.gps_em;
$$;
REVOKE EXECUTE ON FUNCTION public.transurban_publicar_gps(jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.transurban_publicar_gps(jsonb) TO service_role;
COMMIT;
NOTIFY pgrst, 'reload schema';
