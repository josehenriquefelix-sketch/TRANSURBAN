-- Preparação não destrutiva para public.cidade e public.linha_onibus.
-- Executar no SQL Editor do projeto da equipe. Nenhum DROP/DELETE.
BEGIN;
CREATE TABLE IF NOT EXISTS public.cidade (
 id_cidade INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nome VARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS public.linha_onibus (
 id_linha INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 id_cidade INTEGER NOT NULL REFERENCES public.cidade(id_cidade) ON DELETE RESTRICT,
 codigo VARCHAR(20) NOT NULL,
 nome VARCHAR(120) NOT NULL,
 UNIQUE(id_cidade,codigo)
);
-- Para tabelas anteriores, cria a FK apenas se não houver uma equivalente.
DO $$
BEGIN
 IF NOT EXISTS (SELECT 1 FROM pg_constraint c WHERE c.conrelid='public.linha_onibus'::regclass AND c.contype='f' AND c.confrelid='public.cidade'::regclass AND c.conkey=ARRAY[(SELECT attnum FROM pg_attribute WHERE attrelid='public.linha_onibus'::regclass AND attname='id_cidade')]::smallint[]) THEN
  ALTER TABLE public.linha_onibus ADD CONSTRAINT fk_linha_cidade FOREIGN KEY(id_cidade) REFERENCES public.cidade(id_cidade) ON DELETE RESTRICT;
 END IF;
 IF EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.linha_onibus'::regclass AND contype='f' AND confrelid='public.cidade'::regclass AND confdeltype NOT IN ('a','r')) THEN
  RAISE EXCEPTION 'FK existente permite exclusão em cascata ou alteração do vínculo. Revise antes de continuar.';
 END IF;
END $$;
CREATE UNIQUE INDEX IF NOT EXISTS transurban_cidade_nome_unique ON public.cidade(nome);
CREATE UNIQUE INDEX IF NOT EXISTS transurban_linha_codigo_unique ON public.linha_onibus(id_cidade,codigo);
GRANT USAGE ON SCHEMA public TO service_role;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.cidade,public.linha_onibus TO service_role;
ALTER TABLE public.cidade ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.linha_onibus ENABLE ROW LEVEL SECURITY;
COMMIT;
-- Depois executar 04_ids_automaticos_existentes.sql para IDs e permissões das sequências.
-- Conferência (a cidade não é copiada para linha_onibus):
SELECT l.id_linha,l.codigo,l.nome,l.id_cidade,c.nome AS cidade
FROM public.linha_onibus l JOIN public.cidade c USING(id_cidade)
ORDER BY l.id_linha;
