-- SOMENTE PARA BANCO DE TESTES AUTORIZADO SEM ESTAS DUAS TABELAS.
-- Execute 01_auditar_supabase.sql antes. Se uma tabela já existir, esta
-- transação falha sem substituir tabelas nem apagar registros.
BEGIN;

CREATE TABLE public.cidade (
    id_cidade INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL
);

CREATE TABLE public.linha_onibus (
    id_linha INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cidade INTEGER NOT NULL,
    codigo VARCHAR(20) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    CONSTRAINT fk_linha_onibus_cidade
        FOREIGN KEY (id_cidade) REFERENCES public.cidade(id_cidade)
);

CREATE INDEX ix_linha_onibus_id_cidade ON public.linha_onibus(id_cidade);

-- O frontend acessa a API, não o banco com credenciais públicas.
-- Não criamos políticas abertas para anon/authenticated.
ALTER TABLE public.cidade ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.linha_onibus ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.cidade, public.linha_onibus FROM PUBLIC;

DO $$
DECLARE
    role_name TEXT;
    sequence_name TEXT;
BEGIN
    FOR sequence_name IN
        SELECT pg_get_serial_sequence('public.cidade', 'id_cidade')
        UNION ALL
        SELECT pg_get_serial_sequence('public.linha_onibus', 'id_linha')
    LOOP
        EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC', sequence_name);
    END LOOP;
    FOR role_name IN
        SELECT rolname FROM pg_roles WHERE rolname IN ('anon', 'authenticated')
    LOOP
        EXECUTE format('REVOKE ALL ON TABLE public.cidade, public.linha_onibus FROM %I', role_name);
        FOR sequence_name IN
            SELECT pg_get_serial_sequence('public.cidade', 'id_cidade')
            UNION ALL
            SELECT pg_get_serial_sequence('public.linha_onibus', 'id_linha')
        LOOP
            EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM %I', sequence_name, role_name);
        END LOOP;
    END LOOP;
END $$;

COMMIT;
